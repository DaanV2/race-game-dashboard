// Command accessors is a go:generate tool that emits Get/Set methods for the
// exported fields of every exported struct declared in a Go source file.
//
// Array and slice fields get an indexed accessor (Get/Set take an index)
// instead of a whole-value accessor, since copying a large fixed-size array
// in and out by value is rarely what's wanted.
//
// Usage, as a go:generate directive placed in the source file to generate
// accessors for:
//
//	//go:generate go run github.com/daanv2/race-game-dashboard/tools/gen/accessors
//
// By default it generates accessors for every exported struct declared in
// the file. Pass -type with a comma-separated list to restrict it to
// specific struct names:
//
//	//go:generate go run github.com/daanv2/race-game-dashboard/tools/gen/accessors -type CarDamageData,LapHistoryData
//
// It relies on the GOFILE environment variable that `go generate` sets, and
// writes its output next to the source file as "<file>_accessors_gen.go".
// It can also be run directly against a file for testing:
//
//	go run ./tools/gen/accessors path/to/file.go
//	go run ./tools/gen/accessors -type CarDamageData path/to/file.go
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	typeNames := flag.String("type", "", "comma-separated list of struct names to generate accessors for (default: all exported structs)")
	ignoreFields := flag.String("ignore-field", "", "comma-separated list of field names to ignore")
	flag.Parse()

	filename := os.Getenv("GOFILE")
	if filename == "" && flag.NArg() > 0 {
		filename = flag.Arg(0)
	}
	if filename == "" {
		fmt.Fprintln(os.Stderr, "accessors: no input file (expected GOFILE env var or a file argument)")
		os.Exit(1)
	}

	if err := run(filename, parseTypeNames(*typeNames), strings.Split(*ignoreFields, ",")); err != nil {
		fmt.Fprintln(os.Stderr, "accessors:", err)
		os.Exit(1)
	}
}

// parseTypeNames splits a comma-separated -type flag value into a set of
// struct names. A nil result means "no filter, include every struct".
func parseTypeNames(value string) map[string]bool {
	if value == "" {
		return nil
	}

	names := make(map[string]bool)
	for name := range strings.SplitSeq(value, ",") {
		if name = strings.TrimSpace(name); name != "" {
			names[name] = true
		}
	}

	return names
}

func run(filename string, only map[string]bool, ignoreFields []string) error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, nil, parser.SkipObjectResolution)
	if err != nil {
		return fmt.Errorf("parse %s: %w", filename, err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/gen/accessors from %s. DO NOT EDIT.\n\n", filepath.Base(filename))
	fmt.Fprintf(&b, "package %s\n\n", file.Name.Name)

	wrote := false
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			continue
		}

		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || !typeSpec.Name.IsExported() {
				continue
			}

			if only != nil && !only[typeSpec.Name.Name] {
				continue
			}

			structType, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}

			if writeStructAccessors(&b, typeSpec.Name.Name, structType, ignoreFields) {
				wrote = true
			}
		}
	}

	if !wrote {
		return nil
	}

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("format generated source: %w\n\n%s", err, b.String())
	}

	outFile := strings.TrimSuffix(filename, filepath.Ext(filename)) + "_accessors_gen.go"

	return os.WriteFile(outFile, formatted, 0o644) // nolint:gosec // Its for a tool, so ignoring file permissions
}

// writeStructAccessors writes Get/Set methods for every exported, named field
// of the struct. Embedded (anonymous) fields are skipped. It reports whether
// it wrote anything.
func writeStructAccessors(b *strings.Builder, structName string, st *ast.StructType, ignoreFields []string) bool {
	wrote := false

	for _, field := range st.Fields.List {
		for _, name := range field.Names {
			if slices.Contains(ignoreFields, name.Name) {
				continue
			}

			if !name.IsExported() {
				continue
			}

			writeFieldAccessors(b, structName, name.Name, field.Type)
			wrote = true
		}
	}

	return wrote
}

func writeFieldAccessors(b *strings.Builder, structName, fieldName string, typ ast.Expr) {
	if arrayType, ok := typ.(*ast.ArrayType); ok {
		elemType := types.ExprString(arrayType.Elt)

		fmt.Fprintf(b, "// Get%s returns the %s element of [%s] at index\n", fieldName, fieldName, structName)
		fmt.Fprintf(b, "func (data *%s) Get%s(index int) %s { return data.%s[index] }\n\n", structName, fieldName, elemType, fieldName)

		fmt.Fprintf(b, "// Set%s stores the %s element of [%s] at index\n", fieldName, fieldName, structName)
		fmt.Fprintf(b, "func (data *%s) Set%s(index int, v %s) { data.%s[index] = v }\n\n", structName, fieldName, elemType, fieldName)

		return
	}

	typeStr := types.ExprString(typ)

	fmt.Fprintf(b, "// Get%s returns the %s of [%s]\n", fieldName, fieldName, structName)
	fmt.Fprintf(b, "func (data *%s) Get%s() %s { return data.%s }\n\n", structName, fieldName, typeStr, fieldName)

	fmt.Fprintf(b, "// Set%s stores the %s of [%s]\n", fieldName, fieldName, structName)
	fmt.Fprintf(b, "func (data *%s) Set%s(v %s) { data.%s = v }\n\n", structName, fieldName, typeStr, fieldName)
}
